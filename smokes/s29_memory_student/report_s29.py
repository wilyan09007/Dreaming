"""Builds tables.md from results.json: every number in RESULTS.md comes from here.  python report_s29.py [results.json] [tables.md]"""
import json, sys
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent
R = json.load(open(sys.argv[1] if len(sys.argv) > 1 else HERE / "results.json"))
OUTF = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "tables.md"
L = []
def P(*s): L.append(" ".join(str(x) for x in s))
def tab(head, rows): P("| " + " | ".join(head) + " |"); P("|" + "---|" * len(head)); [P("| " + " | ".join(str(c) for c in r) + " |") for r in rows]; P()
def ms(v, nd=3):
    v = [x for x in v if x is not None]
    if not v: return "-"
    return f"{np.mean(v):.{nd}f} +- {np.std(v, ddof=1):.{nd}f}" if len(v) > 1 else f"{v[0]:.{nd}f}"
def mean(v, nd=3): v = [x for x in v if x is not None]; return f"{np.mean(v):.{nd}f}" if v else "-"
def sec(f, name):
    try: f()
    except Exception as e: P(f"_{name}: not available ({type(e).__name__}: {e})_\n")

WORLDS = ["banking77", "clinc150", "clinc45"]; ARMS = ["LR", "Hopfield", "kNN10", "Prototype", "HDC", "Hopfield+synth", "LR+synth"]
A = R.get("A", []); META = R.get("meta", {})
idx = {}
for c in A: idx.setdefault((c["world"], c["n"], c["arm"]), {})[c["split"]] = c
def ns(w): return sorted({c["n"] for c in A if c["world"] == w})
def vals(w, n, arm, f):
    d = idx.get((w, n, arm), {}); return [f(d[s]) for s in sorted(d)]
acc = lambda c: c["acc"]
cov = lambda b: (lambda c: c["cert"][b]["cov"])
err = lambda b: (lambda c: c["cert"][b]["err"])
def paired(w, n, a, b, f):
    da, db = idx.get((w, n, a), {}), idx.get((w, n, b), {}); ss = sorted(set(da) & set(db)); return np.array([f(da[s]) - f(db[s]) for s in ss])

P("# S29 tables (generated by report_s29.py from results.json)\n")
m = META
P(f"GPU {m.get('gpu')}, torch {m.get('torch')}, CUDA {m.get('cuda')}, {m.get('cpus')} CPUs. Worlds: {json.dumps(m.get('worlds'))}. Tiny wiring run: {m.get('tiny')}.\n")
if R.get("errors"): P("**Section errors:** " + "; ".join(f"{e['section']}" for e in R["errors"]) + "\n")
P(f"Section seconds: {json.dumps({k: round(v) for k, v in m.get('section_secs', {}).items()})}\n")
if m.get("clinc_seeded_labels"): P(f"CLINC labels with cached LLM-written examples ({len(m['clinc_seeded_labels'])}): {', '.join(m['clinc_seeded_labels'])}\n")
if m.get("delete_token"): P(f"Deletion token: {m['delete_token']}\n")

# ------------------------------------------------------------------------------------------------ A
def secA():
    for w in WORLDS:
        if not ns(w): continue
        arms = [a for a in ARMS if any(k[0] == w and k[2] == a for k in idx)]
        P(f"## A. Rows ladder: {w}\n")
        for title, f, nd in (("Accuracy on the holdout rows (mean +- s.d. over 5 splits)", acc, 3), ("Certified coverage at a 5% budget (mean +- s.d.)", cov("0.05"), 3), ("Certified coverage at a 2% budget", cov("0.02"), 3), ("Certified coverage at a 10% budget", cov("0.1"), 3)):
            P(f"### {w}: {title}\n"); tab(["rows"] + arms, [[n] + [ms(vals(w, n, a, f), nd) for a in arms] for n in ns(w)])
        P(f"### {w}: realized error above the 5% cutoff (mean over the splits that certified something; k/5 = how many did)\n")
        def e5(n, a):
            v = vals(w, n, a, err("0.05")); ok = [x for x in v if x is not None]; return f"{np.mean(ok):.3f} ({len(ok)}/{len(v)})" if ok else f"- (0/{len(v)})"
        tab(["rows"] + arms, [[n] + [e5(n, a) for a in arms] for n in ns(w)])
        mx = {a: max([x for n in ns(w) for b in ("0.02", "0.05", "0.1") for x in vals(w, n, a, err(b)) if x is not None] or [float("nan")]) for a in arms}
        P(f"Largest realized error in any split above any cutoff, per arm (2/5/10% budgets pooled; compare each with its own budget in the cells above): {json.dumps({a: round(v, 3) for a, v in mx.items()})}\n")
        viol = {}
        for a in arms:
            k = t = 0
            for n in ns(w):
                for b in (0.02, 0.05, 0.1):
                    for x in vals(w, n, a, err(str(b))):
                        if x is not None: t += 1; k += x > b
            viol[a] = f"{k}/{t}"
        P(f"Splits where realized holdout error exceeded the budget that was certified (count / certified splits, all budgets): {json.dumps(viol)}\n")
        base = [a for a in arms if a != "LR"]
        P(f"### {w}: paired difference to LR, accuracy (arm - LR, mean +- s.d. over the 5 splits)\n")
        tab(["rows"] + base, [[n] + [ms(paired(w, n, a, "LR", acc), 3) if len(paired(w, n, a, "LR", acc)) else "-" for a in base] for n in ns(w)])
        for b in ("0.05", "0.02", "0.1"):
            P(f"### {w}: paired difference to LR, certified coverage at {float(b):.0%} (arm - LR)\n")
            tab(["rows"] + base, [[n] + [ms(paired(w, n, a, "LR", cov(b)), 3) if len(paired(w, n, a, "LR", cov(b))) else "-" for a in base] for n in ns(w)])
        # crossover
        P(f"### {w}: crossover (smallest ladder size from which LR is ahead of the memory arm at every larger size; also the sign pattern, '+' = memory ahead, '-' = LR ahead, '*' = |mean| > 2 s.e.)\n")
        rows = []
        for a, bname in (("Hopfield", "LR"), ("Hopfield+synth", "LR"), ("Hopfield+synth", "LR+synth"), ("Prototype", "LR"), ("HDC", "LR"), ("kNN10", "LR")):
            if not any(k[0] == w and k[2] == a for k in idx): continue
            for mname, f in (("accuracy", acc), ("cov 2%", cov("0.02")), ("cov 5%", cov("0.05")), ("cov 10%", cov("0.1"))):
                diffs = {n: paired(w, n, a, bname, f) for n in ns(w)}; diffs = {n: d for n, d in diffs.items() if len(d)}
                if not diffs: continue
                nn = sorted(diffs); pat = "".join(("+" if diffs[n].mean() >= 0 else "-") + ("*" if abs(diffs[n].mean()) > 2 * diffs[n].std(ddof=1) / np.sqrt(len(diffs[n])) else "") + " " for n in nn)
                cross = None
                for i, n in enumerate(nn):
                    if all(diffs[k].mean() < 0 for k in nn[i:]): cross = n; break
                K = META["worlds"][w]["K"]
                rows.append([f"{a} vs {bname}", mname, f"{cross} ({cross / K:.1f} rows/label)" if cross is not None else ("LR never overtakes" if diffs[nn[-1]].mean() >= 0 else "-"), pat.strip(), " ".join(str(n) for n in nn)])
        tab(["pair", "metric", "crossover rows", "sign pattern by ladder size", "sizes"], rows)
        P(f"### {w}: Hopfield beta picked on calibration accuracy (median, min-max over splits)\n")
        bs = lambda a, n: (lambda v: f"{int(np.median(v))} ({int(min(v))}-{int(max(v))})")([c["beta"] for c in idx[(w, n, a)].values()]) if (w, n, a) in idx else "-"
        tab(["arm"] + [str(n) for n in ns(w)], [[a] + [bs(a, n) for n in ns(w)] for a in ("Hopfield", "Hopfield+synth") if any(k[0] == w and k[2] == a for k in idx)])
        if w == "clinc150":
            P("### clinc150: accuracy on holdout rows of the 45 seeded labels / of the other 105 labels\n")
            tab(["rows"] + arms, [[n] + [f"{mean(vals(w, n, a, lambda c: c.get('acc_seeded')))} / {mean(vals(w, n, a, lambda c: c.get('acc_unseeded')))}" for a in arms] for n in ns(w)])
        P(f"### {w}: LR fit seconds (GPU L-BFGS, mean) and L-BFGS iterations / final max-gradient\n")
        tab(["rows", "fit s", "iters", "max |grad|"], [[n, mean(vals(w, n, "LR", lambda c: c.get("fit_s")), 2), mean(vals(w, n, "LR", lambda c: c.get("iters")), 0), f"{np.max(vals(w, n, 'LR', lambda c: c.get('gnorm'))):.1e}"] for n in ns(w) if (w, n, "LR") in idx])
sec(secA, "A")

def lrcheck():
    P("## LR cross-check: GPU L-BFGS vs sklearn LogisticRegression(C=10, max_iter=2000), same rows, split 0\n")
    tab(["world", "rows", "torch s", "sklearn s", "torch iters", "sklearn iters", "argmax agreement", "max |dp|", "acc torch", "acc sklearn", "cov5 torch", "cov5 sklearn"],
        [[c["world"], c["n"], f"{c['torch_s']:.1f}", f"{c['sklearn_s']:.1f}", c["torch_iter"], c["sklearn_iter"], f"{c['agree']:.4f}", f"{c['max_dp']:.4f}", f"{c['acc_torch']:.4f}", f"{c['acc_sklearn']:.4f}", f"{c['cov5_torch']:.3f}", f"{c['cov5_sklearn']:.3f}"] for c in META["lr_check"]])
sec(lrcheck, "lr_check")

# ------------------------------------------------------------------------------------------------ B
def secB():
    B = R["B"]; arms = list(dict.fromkeys(c["arm"] for c in B)); P("## B. Class imbalance (Banking77, 3080 rows; Zipf: class counts proportional to 1/rank, truncated at the class's available rows; uniform: equal counts; balanced test set)\n")
    g = lambda d, a: sorted([c for c in B if c["design"] == d and c["arm"] == a], key=lambda c: c["split"])
    z0 = [c for c in B if c["design"] == "zipf" and c["arm"] == arms[0]]; u0 = [c for c in B if c["design"] == "uniform" and c["arm"] == arms[0]]
    P(f"Training class counts (mean over splits): zipf max {mean([c['rows_max'] for c in z0], 0)}, min {mean([c['rows_min'] for c in z0], 0)}, rarest-20 mean {mean([c['rows_rare20_mean'] for c in z0], 1)}, top-20 mean {mean([c['rows_top20_mean'] for c in z0], 1)}; uniform max {mean([c['rows_max'] for c in u0], 0)}, min {mean([c['rows_min'] for c in u0], 0)}.\n")
    for d in ("zipf", "uniform"):
        P(f"### {d}: mean +- s.d. over {len(z0)} splits\n")
        tab(["arm", "accuracy", "macro-F1", "recall rarest 20 classes", "recall top-20 classes", "share of predictions in top-20 classes", "cert. cov 5%", "realized err 5%", "cert. cov 2%", "cert. cov 10%"],
            [[a, ms([c["acc"] for c in g(d, a)]), ms([c["macro_f1"] for c in g(d, a)]), ms([c["rare20_recall"] for c in g(d, a)]), ms([c["top20_recall"] for c in g(d, a)]), ms([c["pred_in_top20"] for c in g(d, a)]),
              ms([c["cert"]["0.05"]["cov"] for c in g(d, a)]), mean([c["cert"]["0.05"]["err"] for c in g(d, a)]), ms([c["cert"]["0.02"]["cov"] for c in g(d, a)]), ms([c["cert"]["0.1"]["cov"] for c in g(d, a)])] for a in arms])
    P("### zipf minus uniform (paired by split), mean +- s.d.\n")
    def pd(a, f): return ms([f(x) - f(y) for x, y in zip(g("zipf", a), g("uniform", a))])
    tab(["arm", "d accuracy", "d macro-F1", "d recall rarest 20", "d cert. cov 5%"], [[a, pd(a, lambda c: c["acc"]), pd(a, lambda c: c["macro_f1"]), pd(a, lambda c: c["rare20_recall"]), pd(a, lambda c: c["cert"]["0.05"]["cov"])] for a in arms])
    P("### Hopfield beta picked (median, min-max)\n")
    tab(["design", "arm", "beta"], [[d, a, f"{int(np.median([c['beta'] for c in g(d, a)]))} ({int(min(c['beta'] for c in g(d, a)))}-{int(max(c['beta'] for c in g(d, a)))})"] for d in ("zipf", "uniform") for a in arms if a.startswith("Hopfield")])
sec(secB, "B")

# ------------------------------------------------------------------------------------------------ C
def secC():
    C = R["C"]; P(f"## C. Deletion from the 3080-row Banking77 memory (token deleted in case 'token': {META.get('delete_token')}); fresh calibration slice of 500 test rows after deletion; holdout = the other test rows\n")
    names = {"classes": "(i) all rows of 10 random classes", "random20": "(ii) 20% random rows", "token": "(iii) all rows containing the token"}
    for case, title in names.items():
        rows = []
        for arm, stage in (("Hopfield", "before"), ("Hopfield", "after_stale_cert"), ("Hopfield", "after_recert"), ("Hopfield", "after_recert_remaining_traffic"), ("LR", "before"), ("LR", "after_no_refit"), ("LR", "after_refit")):
            cs = [c for c in C if c["case"] == case and c["arm"] == arm and c["stage"] == stage]
            if not cs: continue
            rows.append([arm, stage, mean([c.get("acc") for c in cs]), mean([c.get("cov") for c in cs]), mean([c.get("err") for c in cs]), mean([c.get("pred_deleted_label") for c in cs], 4), mean([c.get("acc_token_rows") for c in cs]) if case == "token" else "-",
                         mean([c.get("rows_kept") for c in cs], 0), mean([c.get("delete_ms") for c in cs], 2), mean([c.get("delete_plus_recert_ms") for c in cs], 1), mean([c.get("refit_s_gpu") for c in cs], 2), mean([c.get("refit_s_sklearn_cpu") for c in cs], 1)])
        P(f"### {title} (mean over {len({c['split'] for c in C})} splits)\n")
        tab(["arm", "stage", "accuracy", "cov 5%", "realized err 5%", "share of predictions that are a deleted label", "accuracy on test rows containing the token", "rows kept", "delete ms", "delete + re-pick beta + recertify ms", "LR refit s (GPU)", "LR refit s (sklearn CPU, split 0)"], rows)
    mx = max([c["pred_deleted_label"] for c in C if c["case"] == "classes" and c["arm"] == "Hopfield" and c["stage"].startswith("after") and "pred_deleted_label" in c] or [float("nan")])
    P(f"Largest share of Hopfield predictions that were a deleted label after deletion of classes, any split: {mx}\n")
    P(f"LR fit on the full 3080 rows (GPU s, mean): {mean([c.get('refit_s_gpu') for c in C if c['stage'] == 'fit_full_s_gpu'], 2)}\n")
sec(secC, "C")

# ------------------------------------------------------------------------------------------------ D
def secD():
    D = R["D"]; P(f"## D. Query cost (batch 1; beta {D.get('beta')}; 1M-row memory = base rows tiled with Gaussian noise sd {D.get('noise_sd')} per dimension, renormalised)\n")
    f = lambda r, k, q="p50": f"{r[k][q]:.3f}" if k in r else "-"
    tab(["rows", "memory MB", "CPU 1 thread ms p50", "p95", "GPU batch 1 ms p50 (dense one-hot)", "p95", "GPU batch 1 ms p50 (index_add)", "GPU batch 64: ms per query p50"],
        [[r["N"], f"{r['memory_mb']:.0f}", f(r, "cpu_1thread"), f(r, "cpu_1thread", "p95"), f(r, "gpu_batch1_dense"), f(r, "gpu_batch1_dense", "p95"), f(r, "gpu_batch1_scatter"), f(r, "gpu_batch64_per_query")] for r in D["flat"]])
    P("### Approximate index (hnswlib, inner product, M=16, ef_construction=100; top-50 neighbours, softmax over them). Query time = 1 thread, batch 1. Recall of the exact top-50; share of predictions that change vs the exact full read; 'exact top-50 read' = exact neighbours truncated to 50 (isolates truncation from index error)\n")
    rows = []
    for r in D["ann"]:
        if "skipped" in r: rows.append([r["N"], "-", "-", "-", "-", "-", "-", "-", r["skipped"]]); continue
        rows.append([r["N"], r["ef"], f"{r['build_s']:.1f} ({r['build_threads']} threads)", f"{r['query']['p50'] * 1000:.0f}", f"{r['query']['p95'] * 1000:.0f}", f"{r['recall50']:.3f}", f"{r['changed_vs_exact_full']:.4f}", f"{r['trunc_exact_top50_changed_vs_full']:.4f}", f"{r['queries']} queries"])
    tab(["rows", "ef", "build s", "query us p50", "us p95", "recall@50", "predictions changed vs exact full read", "exact top-50 read changed vs full", "note"], rows)
    P("### Constant-cost heads, CPU 1 thread, batch 1 (ms)\n"); tab(["head", "p50", "p95"], [[k, f"{v['p50']:.4f}", f"{v['p95']:.4f}"] for k, v in D.get("const_heads", {}).items()])
sec(secD, "D")

# ------------------------------------------------------------------------------------------------ E
def secE():
    E = R["E"]; P(f"## E. Determinism (memory of {E['memory_rows']} Banking77 rows, beta {E['beta']}, {E['reps']} repetitions per test; distinct = number of distinct byte-strings / distinct 'label:confidence rounded to 3 decimals')\n")
    tab(["device", "head", "protocol", "n", "distinct raw score bytes", "distinct label+conf(3 dp)"], [[t["device"], t["head"], t["protocol"], t["n"], t["distinct_scores"], t["distinct_label_conf"]] for t in E["tests"]])
    if "thread_count" in E:
        P("### CPU thread count (Hopfield dense read; bytes equal to the 1-thread reference?)\n"); tab(["threads", "batch 1", "batch of 8"], [[k, v["batch1_same_bytes_as_1_thread"], v["batch8_same_bytes_as_1_thread"]] for k, v in E["thread_count"].items()])
    if "ann" in E:
        P("### Approximate index (hnswlib)\n")
        if isinstance(E["ann"], dict): tab(["test", "result"], [[k, v] for k, v in E["ann"].items()])
        else: P(E["ann"] + "\n")
sec(secE, "E")

OUTF.write_text("\n".join(L) + "\n", encoding="utf-8"); print("wrote", OUTF, len(L), "lines")
